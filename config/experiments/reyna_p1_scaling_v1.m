function experiment = reyna_p1_scaling_v1()
% REYNA_P1_SCALING_V1
% -----------------------------------------------------------------------
% Locked experiment contract for Reyna pre-surgery scaling comparison.
%
% The contract deliberately separates fair-prior runs from the current
% operational recipe.  It does not modify the clinical profile, target
% tiers, or acceptance gates.
% -----------------------------------------------------------------------

experiment = struct();
experiment.id = 'reyna_p1_scaling_v1';
experiment.version = '2026-08-27';
experiment.patient_label = 'reyna';
experiment.scenario = 'pre_surgery';
experiment.primary_metrics = {'RAP_mean','PAP_mean','SAP_mean','QpQs','CO_Lmin'};
experiment.gsa_training_samples = 128;
experiment.default_repeats = 3;
experiment.clinical_factory = 'patient_reyna';
experiment.target_governance = 'reyna_pre_surgery recipe; primary metrics and clinical values locked';
experiment.forbidden_changes = {'clinical values','target tiers','primary RMSE membership', ...
    'acceptance thresholds','historical run folders'};

arm_template = struct( ...
    'id', '', ...
    'label', '', ...
    'scaling_mode', '', ...
    'historical_seeds_disabled', false, ...
    'expected_seed_policy', '', ...
    'hypothesis', '');

experiment.arms = repmat(arm_template, 4, 1);
experiment.arms(1) = make_arm( ...
    'fair_prior_zhang', 'Fair prior - Zhang', 'zhang', true, ...
    'disabled_fair_prior', ...
    'Does Zhang reduce the error when historical recipe seeds are removed?');
experiment.arms(2) = make_arm( ...
    'fair_prior_lundquist', 'Fair prior - Lundquist BSA', 'lundquist_bsa', true, ...
    'disabled_fair_prior', ...
    'Does the Lundquist BSA prior retain an advantage without its historical seed?');
experiment.arms(3) = make_arm( ...
    'operational_zhang', 'Current operational recipe - Zhang', 'zhang', false, ...
    'recipe_controlled', ...
    'What is the current Zhang operational result under the existing recipe path?');
experiment.arms(4) = make_arm( ...
    'operational_lundquist', 'Current operational recipe - Lundquist BSA', 'lundquist_bsa', false, ...
    'recipe_controlled', ...
    'What is the current accepted Lundquist operational result?');
end

function arm = make_arm(id, label, scaling_mode, seeds_disabled, seed_policy, hypothesis)
arm = struct( ...
    'id', id, ...
    'label', label, ...
    'scaling_mode', scaling_mode, ...
    'historical_seeds_disabled', seeds_disabled, ...
    'expected_seed_policy', seed_policy, ...
    'hypothesis', hypothesis);
end
